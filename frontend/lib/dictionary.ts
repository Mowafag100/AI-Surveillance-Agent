export const dictionaries: Record<Locale, typeof ar> = { ar, en };

export function translate(locale: Locale, key: string): string {
  const value = (dictionaries[locale] as Record<string, unknown>)[key];
  return typeof value === "string" ? value : key;
}

/** وسم BCP-47 لتنسيق التواريخ حسب اللغة */
export function localeDateTimeTag(locale: Locale): "ar-SA" | "en-US" {
  return locale === "ar" ? "ar-SA" : "en-US";
}
